# ждать, пока не идут часовые задания аналитики (:20 selfheal, :40 quick, :45 reports); ночные окна проверяем отдельно
while true; do
  m=$(date +%M); h=$(date +%H)
  case "$m" in 19|20|39|40|44|45) sleep 20; continue;; esac
  case "$h:$m" in 00:5*|01:0[0-3]|02:5*|03:*|04:*|05:0*|05:1*|05:2*|05:3[0-5]|06:0[5-9]|06:1*|06:2[0-5]) echo "ночное окно заданий аналитики ($h:$m) — стоп"; exit 3;; esac
  break
done
echo "окно свободно: $(date +%T) (время сервера)"
